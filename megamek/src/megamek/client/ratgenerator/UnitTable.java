/**
 * Manages random assignment table generated by RATGenerator.
 *
 * @author Neoancient
 */
public class UnitTable {
    private final static MMLogger LOGGER = MMLogger.create(UnitTable.class);

    @FunctionalInterface
    public interface UnitFilter {
        boolean include(MekSummary ms);
    }

    private static final int CACHE_SIZE = 32;

    private static final LinkedHashMap<Parameters, UnitTable> cache = new LinkedHashMap<>(CACHE_SIZE, 0.75f, true) {

        @Serial
        private static final long serialVersionUID = -8016095510116134800L;

        @Override
        protected boolean removeEldestEntry(Map.Entry<Parameters, UnitTable> entry) {
            return size() >= CACHE_SIZE;
        }
    };

    /**
     * Checks the cache for a previously generated table meeting the criteria. If none is found, generates it and adds
     * it to the cache. This method is provided as a convenience for when there are no excluded roles.
     *
     * @param faction          The faction the table filters for
     * @param unitType         {@link UnitType} constant with the type of unit
     * @param year             the game year
     * @param rating           the unit's equipment rating; if null, the table is not adjusted for unit rating.
     * @param weightClasses    a collection of {@link EntityWeightClass} constants to include in the table; if null or
     *                         empty all weight classes are included
     * @param networkMask      One of the {@link ModelRecord} NETWORK constants, for filtering various C3 systems
     * @param movementModes    the movement modes covered by the table, null/empty for all modes
     * @param roles            {@link MissionRole} types the units should qualify for, null/empty for no role filtering
     * @param roleStrictness   how strongly to apply roles, zero for none/minimal with higher being more restrictive;
     *                         typically no higher than 5
     * @param deployingFaction when using the salvage/isorla mechanism, any omni unit will select the configuration
     *                         based on the faction actually deploying
     *
     * @return table containing units which fit all parameters and their relative weights
     */
    public static UnitTable findTable(FactionRecord faction, int unitType, int year, String rating,
          Collection<Integer> weightClasses, int networkMask, Collection<EntityMovementMode> movementModes,
          Collection<MissionRole> roles, int roleStrictness, FactionRecord deployingFaction) {
        Objects.requireNonNull(faction);
        Parameters params = new Parameters(faction,
              unitType,
              year,
              rating,
              weightClasses,
              networkMask,
              movementModes,
              roles,
              new ArrayList<>(),
              roleStrictness,
              deployingFaction);
        return findTable(params);
    }

    /**
     * Overloaded method, with additional argument for excluded roles
     *
     * @param faction          The faction the table filters for
     * @param unitType         {@link UnitType} constant with the type of unit
     * @param year             the game year
     * @param rating           the unit's equipment rating; if null, the table is not adjusted for unit rating.
     * @param weightClasses    collection of {@link EntityWeightClass} constants to include in the table; if null or
     *                         empty all weight classes are included
     * @param networkMask      One of the {@link ModelRecord} NETWORK constants, for filtering various C3 systems
     * @param movementModes    the movement modes covered by the table, null/empty for all modes
     * @param roles            {@link MissionRole} types the units should qualify for, null/empty for no role filtering
     * @param rolesExcluded    {@link MissionRole} types the units should not contain, null empty to allow all roles
     * @param roleStrictness   how strongly to apply roles, zero for none/minimal with higher being more restrictive;
     *                         typically no higher than 5
     * @param deployingFaction when using the salvage/isorla mechanism, any omni unit will select the configuration
     *                         based on the faction actually deploying
     *
     * @return table containing units which fit all parameters and their relative weights
     */
    public static UnitTable findTable(FactionRecord faction, int unitType, int year, String rating,
          Collection<Integer> weightClasses, int networkMask, Collection<EntityMovementMode> movementModes,
          Collection<MissionRole> roles, Collection<MissionRole> rolesExcluded, int roleStrictness,
          FactionRecord deployingFaction) {
        Objects.requireNonNull(faction);
        Parameters params = new Parameters(faction,
              unitType,
              year,
              rating,
              weightClasses,
              networkMask,
              movementModes,
              roles,
              rolesExcluded,
              roleStrictness,
              deployingFaction);
        return findTable(params);
    }

    /**
     * Provided as a convenience to call findTable while using the faction parameter as the deploying faction
     */

    public static UnitTable findTable(FactionRecord faction, int unitType, int year, String rating,
          Collection<Integer> weightClasses, int networkMask, Collection<EntityMovementMode> movementModes,
          Collection<MissionRole> roles, int roleStrictness) {
        return findTable(faction,
              unitType,
              year,
              rating,
              weightClasses,
              networkMask,
              movementModes,
              roles,
              roleStrictness,
              faction);
    }

    /**
     * Checks cache for a unit table with the given parameters. If none is found, generates one and adds to the cache
     * using a copy of the Parameters object as a key.
     *
     * @param params - the parameters to use in generating the table.
     *
     * @return a generated table matching the parameters
     */
    public static synchronized UnitTable findTable(Parameters params) {
        Objects.requireNonNull(params);
        UnitTable retVal = cache.get(params);
        if (retVal == null) {
            retVal = new UnitTable(params);
            if (retVal.hasUnits()) {
                // Use a copy of the params for the cache key to prevent changing it.
                cache.put(params.copy(), retVal);
            }
        }
        return retVal;
    }

    /** Empties the table cache, so the next lookup builds each table again from the current faction data. */
    static synchronized void clearCache() {
        cache.clear();
    }

    /** Set while a generation that asked for no salvage is running on this thread. */
    private static final ThreadLocal<Boolean> SALVAGE_EXCLUDED = ThreadLocal.withInitial(() -> false);

    /**
     * Runs work with salvage turned off: every unit drawn from any table on this thread meanwhile comes from the
     * table's own faction. Nested calls are fine; salvage stays off until the outermost one returns.
     *
     * @param work the generation to run
     * @param <T>  what the work returns
     *
     * @return what the work returned
     */
    public static <T> T callWithoutSalvage(Supplier<T> work) {
        if (SALVAGE_EXCLUDED.get()) {
            return work.get();
        }
        SALVAGE_EXCLUDED.set(true);
        try {
            return work.get();
        } finally {
            SALVAGE_EXCLUDED.set(false);
        }
    }

    /**
     * Runs work with salvage turned off, as {@link #callWithoutSalvage(Supplier)} does.
     *
     * @param work the generation to run
     */
    public static void runWithoutSalvage(Runnable work) {
        callWithoutSalvage(() -> {
            work.run();
            return null;
        });
    }

    /** @return {@code true} while salvage is turned off on this thread */
    public static boolean isSalvageExcluded() {
        return SALVAGE_EXCLUDED.get();
    }

    private final Parameters key;
    private final List<TableEntry> unitTable = new ArrayList<>();

    int unitTotal;
    /** The chance, from 0 to 100, that a drawn unit is replaced by another faction's salvage. */
    private double salvagePercent;
    /**
     * Where salvage comes from, by relative weight. A source whose table turns out to have no units is dropped, so
     * later draws do not keep trying it.
     */
    private final Map<FactionRecord, Double> salvageSources = new LinkedHashMap<>();

    /**
     * Initializes table based on restrictions provided by a Parameters object
     *
     * @param key a {@link Parameters} structure providing the parameters for generating the table
     */
    protected UnitTable(Parameters key) {
        this.key = key;
        /*
         * Generate the RAT, then go through it to build the NavigableMaps that
         * will be used for random selection.
         */
        if (key.getFaction() != null) {

            // Simple check if the faction is active now
            if (key.getFaction().isActiveInYear(key.getYear())) {

                List<TableEntry> table = RATGenerator.getInstance()
                      .generateTable(key.getFaction(),
                            key.getUnitType(),
                            key.getYear(),
                            key.getRating(),
                            key.getWeightClasses(),
                            key.getNetworkMask(),
                            key.getMovementModes(),
                            key.getRoles(),
                            key.getRoleStrictness(),
                            key.getDeployingFaction());
                Collections.sort(table);

                for (TableEntry entry : table) {
                    if (entry.isUnit()) {
                        unitTotal += entry.weight;
                        unitTable.add(entry);
                    }
                }
                SalvageChance salvageChance = RATGenerator.getInstance()
                      .getSalvageChance(key.getFaction(), key.getYear());
                salvagePercent = salvageChance.percent();
                salvageSources.putAll(salvageChance.factionWeights());
            }
        } else {
            LOGGER.warn("key.getFaction() returned null; likely faction lookup error");
        }
    }

    /**
     * @return - number of entries in the table
     */

    public int getNumEntries() {
        return unitTable.size();
    }

    /**
     * @return the chance that a drawn unit is salvage, and the factions it comes from; sources found to have no units
     *       for this table's parameters are left out
     */
    public synchronized SalvageChance getSalvageChance() {
        return new SalvageChance(salvagePercent, salvageSources);
    }

    /**
     * @param index index of the {@link TableEntry}
     *
     * @return - the entry at the indicated index
     */
    private TableEntry getEntry(int index) {
        try {
            return unitTable.get(index);
        } catch (IndexOutOfBoundsException e) {
            // Can't log from a static context
        }
        return null;
    }

    /**
     * @param index index of the Weight
     *
     * @return - the weight value for the entry at the indicated index
     */
    public int getEntryWeight(int index) {
        TableEntry te = getEntry(index);
        return (te != null) ? te.weight : 0;
    }

    /**
     * @param index index of the Text
     *
     * @return - a string representing the entry at the indicated index for use in the table
     */
    public String getEntryText(int index) {
        return unitTable.get(index).getUnitEntry().getName();
    }

    /**
     * @param index index of the Tech Base
     *
     * @return - a string representing the entry at the indicated index for use in the table
     */
    public String getTechBase(int index) {
        return unitTable.get(index).getUnitEntry().isClan() ? "Clan" : "IS";
    }

    /**
     * @param index index of the Unit Role
     *
     * @return - a string representing the entry at the indicated index for use in the table
     */
    public String getUnitRole(int index) {
        return unitTable.get(index).getUnitEntry().getRole().toString();
    }

    /**
     * @param index of the {@link MekSummary}
     *
     * @return - the MekSummary entry for the indicated index, or {@code null} if there is no entry at that index
     */
    public @Nullable MekSummary getMekSummary(int index) {
        TableEntry entry = getEntry(index);
        return (entry != null) ? entry.getUnitEntry() : null;
    }

    /**
     * @param index of the BV
     *
     * @return - the BV of the unit at the indicated index, or 0 if there is no entry at that index
     */
    public int getBV(int index) {
        TableEntry entry = getEntry(index);
        return (entry != null) ? entry.getUnitEntry().getBV() : 0;
    }

    /**
     * @return true if the generated table has any unit entries
     */
    public boolean hasUnits() {
        return !unitTable.isEmpty();
    }

    /**
     * Selects a unit from the full table.
     *
     * @return the selected unit
     */
    public MekSummary generateUnit() {
        return generateUnit(null);
    }

    /**
     * Selects a unit from the entries in the table that pass the filter
     *
     * @param filter - the function that determines which units are permitted; if null, no filter is applied.
     *
     * @return - the selected unit, or null if no units pass the filter.
     */
    public @Nullable MekSummary generateUnit(UnitFilter filter) {
        return generateUnit(filter, List.of());
    }

    /**
     * Selects a unit from the entries in the table that pass the filter.
     *
     * @param filter        the function that determines which units are permitted; if null, no filter is applied
     * @param drawnThisCall units already drawn earlier in the same multi-unit draw, counted toward
     *                      {@link UnitVariety} when it is in force
     *
     * @return the selected unit, or null if no units pass the filter
     */
    private @Nullable MekSummary generateUnit(@Nullable UnitFilter filter, List<MekSummary> drawnThisCall) {
        if (rollsSalvage()) {
            MekSummary salvagedUnit = generateSalvage(filter, drawnThisCall);
            if (salvagedUnit != null) {
                return salvagedUnit;
            }
        }
        return drawFromOwnTable(filter, drawnThisCall);
    }

    /** @return {@code true} if this draw is to be salvage: salvage is allowed and the chance roll succeeds */
    private boolean rollsSalvage() {
        if (isSalvageExcluded() || (salvagePercent <= 0.0)) {
            return false;
        }
        synchronized (this) {
            if (salvageSources.isEmpty()) {
                return false;
            }
        }
        return Compute.randomFloat() * 100.0 < salvagePercent;
    }

    /**
     * Selects a unit from the faction's own entries that pass the filter, never from another faction's salvage.
     *
     * <p>For a pick that must be of one kind, such as an infantry class, where the faction's own table may hold
     * none at this rating: salvage would then be the only source that matches, and the force would fill up with
     * other factions' units instead of trying the faction's own at another rating.</p>
     *
     * @param filter the function that determines which units are permitted; if {@code null}, no filter is applied
     *
     * @return the selected unit, or {@code null} if none of the faction's own units pass the filter
     */
    public @Nullable MekSummary generateUnitWithoutSalvage(@Nullable UnitFilter filter) {
        return drawFromOwnTable(filter, List.of());
    }

    private @Nullable MekSummary drawFromOwnTable(@Nullable UnitFilter filter, List<MekSummary> drawnThisCall) {
        int roll;
        List<TableEntry> useUnitList = unitTable;
        int unitMapSize = unitTotal;
        if (filter != null) {
            useUnitList = unitTable.stream().filter(te -> filter.include(te.getUnitEntry())).toList();
            unitMapSize = useUnitList.stream().mapToInt(te -> te.weight).sum();
        }

        UnitVariety variety = UnitVariety.active();
        if ((variety != null) && (useUnitList.size() > 1)) {
            return drawWithVariety(useUnitList, variety.weightsForDraw(drawnThisCall));
        }

        if (unitMapSize > 0) {
            roll = Compute.randomInt(unitMapSize);
            for (TableEntry te : useUnitList) {
                if (roll < te.weight) {
                    return te.getUnitEntry();
                }
                roll -= te.weight;
            }
        }
        return null;
    }

    /** How finely a scaled weight is kept: a unit's table weight is at most 1000, so totals stay well inside an int. */
    private static final int VARIETY_WEIGHT_SCALE = 100;

    /**
     * Draws from entries whose weights are scaled by {@link UnitVariety}. Every entry keeps some weight, so a unit is
     * never ruled out, only made less likely.
     *
     * @param entries the entries that may be drawn
     * @param weights what the force already holds
     *
     * @return the unit drawn, or {@code null} if no entry has any weight
     */
    private static @Nullable MekSummary drawWithVariety(List<TableEntry> entries, UnitVariety.DrawWeights weights) {
        int[] scaled = new int[entries.size()];
        int total = 0;
        for (int index = 0; index < entries.size(); index++) {
            TableEntry entry = entries.get(index);
            if (entry.weight > 0) {
                double factor = weights.factor(entry.getUnitEntry());
                scaled[index] = Math.max(1, (int) Math.round(entry.weight * factor * VARIETY_WEIGHT_SCALE));
                total += scaled[index];
            }
        }
        return (total > 0) ? entries.get(pickIndex(scaled, Compute.randomInt(total))).getUnitEntry() : null;
    }

    /**
     * @param weights weights, none negative
     * @param roll    a number from zero to one less than their total
     *
     * @return the index the roll lands on
     */
    static int pickIndex(int[] weights, int roll) {
        int remaining = roll;
        for (int index = 0; index < weights.length; index++) {
            if (remaining < weights[index]) {
                return index;
            }
            remaining -= weights[index];
        }
        return weights.length - 1;
    }

    /**
     * Selects a number of units from the table.
     *
     * @param num - the number of units to be generated.
     *
     * @return - a list of randomly generated units
     */
    public ArrayList<MekSummary> generateUnits(int num) {
        return generateUnits(num, null);
    }

    /**
     * Selects a number of units from the table with a filter.
     *
     * @param num    - the number of units to be generated.
     * @param filter - the function that determines which units are permitted; if null, no filter is applied.
     *
     * @return - a list of randomly generated units
     */
    public ArrayList<MekSummary> generateUnits(int num, UnitFilter filter) {
        ArrayList<MekSummary> retVal = new ArrayList<>();
        for (int i = 0; i < num; i++) {
            // The units drawn so far will sit together, so they count against each other under UnitVariety.
            MekSummary ms = generateUnit(filter, retVal);
            if (ms != null) {
                retVal.add(ms);
            }
        }
        return retVal;
    }

    /**
     * Picks a faction from the salvage sources by weight and draws from its table, built with the same parameters as
     * this one but five years earlier. The draw comes from that faction's own units only, so salvage never chains on to
     * a third faction. A source whose table has no units is dropped and another is picked, until a source with units
     * is found or none are left.
     *
     * @param filter        passed on to the draw from the salvage faction's table
     * @param drawnThisCall units already drawn earlier in the same multi-unit draw
     *
     * @return a unit of another faction, or {@code null} if no source has units that meet the parameters and filter
     */
    private @Nullable MekSummary generateSalvage(@Nullable UnitFilter filter, List<MekSummary> drawnThisCall) {
        FactionRecord source;
        while ((source = pickSalvageSource()) != null) {
            UnitTable salvage = UnitTable.findTable(source,
                  key.getUnitType(),
                  key.getYear() - 5,
                  key.getRating(),
                  key.getWeightClasses(),
                  key.getNetworkMask(),
                  key.getMovementModes(),
                  key.getRoles(),
                  key.getRoleStrictness(),
                  key.getFaction());
            if (salvage.hasUnits()) {
                MekSummary salvagedUnit = salvage.drawFromOwnTable(filter, drawnThisCall);
                LOGGER.debug("[ForceGen][Salvage] {}: drew {} from {} salvage", key.getFaction().getKey(),
                      (salvagedUnit == null) ? "nothing that passes the filter" : salvagedUnit.getName(),
                      source.getKey());
                return salvagedUnit;
            }
            LOGGER.debug("[ForceGen][Salvage] {}: {} has no units for this table; dropped as a salvage source",
                  key.getFaction().getKey(), source.getKey());
            synchronized (this) {
                salvageSources.remove(source);
            }
        }
        return null;
    }

    /** @return a salvage source picked by weight, or {@code null} if there are none left */
    private synchronized @Nullable FactionRecord pickSalvageSource() {
        double total = 0.0;
        for (double weight : salvageSources.values()) {
            total += weight;
        }
        if (total <= 0.0) {
            return null;
        }
        double roll = Compute.randomFloat() * total;
        FactionRecord last = null;
        for (Map.Entry<FactionRecord, Double> entry : salvageSources.entrySet()) {
            last = entry.getKey();
            if (roll < entry.getValue()) {
                return last;
            }
            roll -= entry.getValue();
        }
        // Rounding can leave the roll a hair past the last weight.
        return last;
    }

    /*
     * A tuple that contains either a salvage or a faction entry along with its
     * relative weight.
     * in the table.
     */
    public static class TableEntry implements Comparable<TableEntry> {
        int weight;
        Object entry;

        public TableEntry(int weight, Object entry) {
            this.weight = weight;
            this.entry = entry;
        }

        public MekSummary getUnitEntry() {
            return (MekSummary) entry;
        }

        public FactionRecord getSalvageFaction() {
            return (FactionRecord) entry;
        }

        public boolean isUnit() {
            return entry instanceof MekSummary;
        }

        @Override
        public int compareTo(@Nonnull TableEntry other) {
            if (entry instanceof MekSummary && other.entry instanceof FactionRecord) {
                return 1;
            }
            if (entry instanceof FactionRecord && other.entry instanceof MekSummary) {
                return -1;
            }
            return toString().compareTo(other.toString());
        }

        @Override
        public String toString() {
            if (entry instanceof MekSummary) {
                return ((MekSummary) entry).getName();
            }
            return entry.toString();
        }
    }

}
